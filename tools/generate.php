<?php

/*
 * Generates the binding from tools/api.json (tools/extract.php) and
 * tools/bindings.php (the per-function decisions a header cannot state):
 *
 *   stubs/types.stub.php      value struct classes, handle classes, interfaces
 *   stubs/constants.stub.php  enums and #defines
 *   stubs/functions.stub.php  every bound function
 *   src/gen/types.c|h         class tables, conversions, handle kinds
 *   src/gen/functions.c       function bodies
 *
 *   php84 tools/generate.php && php84 /opt/homebrew/opt/php@8.4/lib/php/build/gen_stub.php stubs
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$api = json_decode(file_get_contents("$root/tools/api.json"), true, 512, JSON_THROW_ON_ERROR);
$bindings = require "$root/tools/bindings.php";

require __DIR__ . '/gen/model.php';
require __DIR__ . '/gen/types.php';
require __DIR__ . '/gen/functions.php';
require __DIR__ . '/gen/constants.php';

$model = new Model($api, $bindings, file_get_contents("$root/lib/miniaudio/miniaudio.h"));

@mkdir("$root/src/gen", 0777, true);

file_put_contents("$root/stubs/constants.stub.php", constants_stub($model));
[$typesStub, $typesC, $typesH] = types_output($model);
file_put_contents("$root/stubs/types.stub.php", $typesStub);
file_put_contents("$root/src/gen/types.c", $typesC);
file_put_contents("$root/src/gen/types.h", $typesH);
$tr = "/* Generated by tools/generate.php. Do not edit. Implemented in src/callbacks.c. */\n\n#ifndef PHPMA_GEN_TRAMPOLINES_H\n#define PHPMA_GEN_TRAMPOLINES_H\n\n#include \"miniaudio.h\"\n\n";
foreach ($GLOBALS['trampolines'] ?? [] as $name => [$cb, $class, $field]) {
    $type = $model->callbacks[$cb] ?? $cb;
    $tr .= preg_replace('/\\(\\*\\)/', $name, $type, 1) . ";\n";
}
$tr .= "\n#endif\n";
[$fnStub, $fnC, $report] = functions_output($model);
file_put_contents("$root/stubs/functions.stub.php", $fnStub);
file_put_contents("$root/src/gen/functions.c", $fnC);
foreach ($GLOBALS['fn_trampolines'] ?? [] as $name => $type) {
    $tr = str_replace("\n#endif\n", preg_replace('/\\(\\*\\)/', $name, $type, 1) . ";\n\n#endif\n", $tr);
}
file_put_contents("$root/src/gen/trampolines.h", $tr);

fwrite(STDERR, $report);
foreach (array_unique($GLOBALS['unclassified'] ?? []) as $u) {
    fwrite(STDERR, "FIELD $u\n");
}
